<script>
window.openCheckoutModal = function(productName, price) {
    var modal = document.getElementById('checkout-modal');
    if (!modal) return;
    
    var title = document.getElementById('checkout-modal-title');
    var desc = document.getElementById('checkout-modal-desc');
    var waBtn = document.getElementById('checkout-wa-btn');
    
    if (productName) {
        title.textContent = 'Checkout: ' + productName;
        desc.textContent = 'Pilih saluran pembelian resmi liefmarket untuk ' + productName + (price ? ' (' + price + ')' : '') + '.';
        var waText = 'Halo admin liefmarket, saya ingin memesan ' + productName + (price ? ' seharga ' + price : '') + '. Apakah stok masih tersedia?';
        waBtn.href = 'https://wa.me/6282342143876?text=' + encodeURIComponent(waText);
    }
    
    modal.style.display = 'flex';
    setTimeout(function() { modal.classList.add('is-active'); }, 10);
};

window.closeCheckoutModal = function() {
    var modal = document.getElementById('checkout-modal');
    if (!modal) return;
    modal.classList.remove('is-active');
    setTimeout(function() { modal.style.display = 'none'; }, 250);
};

document.addEventListener('DOMContentLoaded', function() {
    var closeBtn = document.getElementById('checkout-modal-close');
    var modal = document.getElementById('checkout-modal');
    if (closeBtn) closeBtn.addEventListener('click', window.closeCheckoutModal);
    if (modal) {
        modal.addEventListener('click', function(e) {
            if (e.target === modal) window.closeCheckoutModal();
        });
    }
});
</script>
